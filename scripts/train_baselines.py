#!/usr/bin/env python3
"""Train logistic regression and shallow MLP baselines on cached Criteo data."""

from __future__ import annotations

import argparse
import csv
import logging
from pathlib import Path
from typing import Callable

import torch
from torch import nn

from src.data.module import CriteoBatchIterator
from src.data.pipeline import CATEGORICAL_COLS, NUMERIC_COLS
from src.eval.metrics import compute_auc, compute_logloss
from src.models.baselines import (
    LogisticRegressionModel,
    ShallowMLP,
    evaluate,
    train_epoch,
)

logging.basicConfig(
    format="[%(asctime)s] %(levelname)s:%(name)s:%(message)s",
    level=logging.INFO,
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Train baseline CTR models.")
    parser.add_argument(
        "--manifest",
        type=Path,
        default=Path("data/processed/metadata/split_manifest.json"),
        help="Path to the split manifest generated by preprocess_citeo.py.",
    )
    parser.add_argument("--model", choices=["lr", "mlp"], default="lr")
    parser.add_argument("--batch-size", type=int, default=2048)
    parser.add_argument("--epochs", type=int, default=8)
    parser.add_argument("--lr", type=float, default=7e-4)
    parser.add_argument("--dropout", type=float, default=0.1)
    parser.add_argument("--hash-buckets", type=int, default=1 << 18)
    parser.add_argument("--embedding-dim", type=int, default=8, help="Embedding dimension for categorical features")
    parser.add_argument("--use-embeddings", action="store_true", default=True, help="Use embeddings for categorical features")
    parser.add_argument("--no-embeddings", dest="use_embeddings", action="store_false", help="Use legacy normalization instead of embeddings")
    parser.add_argument("--log-file", type=Path, default=Path("reports/baseline_metrics.csv"))
    parser.add_argument("--device", type=str, default="cpu")
    parser.add_argument("--limit-chunks", type=int, default=None)
    parser.add_argument("--data-root", type=Path, default=None, help="Optional directory containing parquet chunks (overrides paths in manifest)")
    parser.add_argument("--checkpoint", type=Path, default=Path("checkpoints/baseline.pt"))
    return parser.parse_args()


def iterator_factory(args: argparse.Namespace, split: str) -> Callable[[], CriteoBatchIterator]:
    def factory() -> CriteoBatchIterator:
        iterator = CriteoBatchIterator(
            manifest_path=args.manifest,
            split=split,
            batch_size=args.batch_size,
            device=torch.device(args.device),
        )
        if args.data_root is not None:
            data_root_abs = args.data_root.expanduser().resolve()
            file_list = iterator._file_map.get(split, [])
            iterator._file_map[split] = [str(data_root_abs / Path(p).name) for p in file_list]
        if args.limit_chunks:
            iterator._file_map[split] = iterator._file_map[split][: args.limit_chunks]
        return iterator

    return factory


def main() -> None:
    args = parse_args()
    device = torch.device(args.device)
    num_numeric = len(NUMERIC_COLS)
    num_categorical = len(CATEGORICAL_COLS)

    if args.model == "lr":
        model = LogisticRegressionModel(
            num_numeric,
            num_categorical,
            args.hash_buckets,
            embedding_dim=args.embedding_dim,
            use_embeddings=args.use_embeddings,
        )
    else:
        model = ShallowMLP(
            num_numeric,
            num_categorical,
            hash_bucket_size=args.hash_buckets,
            embedding_dim=args.embedding_dim,
            dropout=args.dropout,
            use_embeddings=args.use_embeddings,
        )
    model.to(device)

    logging.info(
        "Model: %s | Embeddings: %s | Embedding Dim: %d | Parameters: %d",
        args.model.upper(),
        "Enabled" if args.use_embeddings else "Disabled",
        args.embedding_dim if args.use_embeddings else 0,
        sum(p.numel() for p in model.parameters()),
    )

    optimizer = torch.optim.Adam(model.parameters(), lr=args.lr)
    loss_fn = nn.BCELoss()

    train_iter_factory = iterator_factory(args, "train")
    val_iter_factory = iterator_factory(args, "val")

    args.log_file.parent.mkdir(parents=True, exist_ok=True)
    args.checkpoint.parent.mkdir(parents=True, exist_ok=True)
    best_auc = 0.0
    with args.log_file.open("w", newline="") as csvfile:
        writer = csv.DictWriter(csvfile, fieldnames=["epoch", "train_loss", "val_loss", "val_auc", "val_logloss"])
        writer.writeheader()
        for epoch in range(1, args.epochs + 1):
            logging.info("Epoch %d/%d", epoch, args.epochs)
            train_stats = train_epoch(model, train_iter_factory(), optimizer, loss_fn)
            val_stats = evaluate(
                model,
                val_iter_factory(),
                loss_fn,
                metric_fns={"auc": compute_auc, "logloss": compute_logloss},
            )
            val_auc = val_stats.metrics.get("auc", 0.0)
            val_logloss = val_stats.metrics.get("logloss", 0.0)

            logging.info(
                "Epoch %d train_loss=%.4f val_loss=%.4f val_auc=%.4f val_logloss=%.4f",
                epoch,
                train_stats.loss,
                val_stats.loss,
                val_auc,
                val_logloss,
            )
            writer.writerow(
                {
                    "epoch": epoch,
                    "train_loss": f"{train_stats.loss:.6f}",
                    "val_loss": f"{val_stats.loss:.6f}",
                    "val_auc": f"{val_auc:.6f}",
                    "val_logloss": f"{val_logloss:.6f}",
                }
            )

            if val_auc > best_auc:
                best_auc = val_auc
                torch.save(
                    {
                        "model_state": model.state_dict(),
                        "config": {
                            "model": args.model,
                            "num_numeric": num_numeric,
                            "num_categorical": num_categorical,
                            "hash_bucket_size": args.hash_buckets,
                            "embedding_dim": args.embedding_dim,
                            "use_embeddings": args.use_embeddings,
                            "dropout": args.dropout,
                        },
                        "epoch": epoch,
                        "val_auc": val_auc,
                        "val_logloss": val_logloss,
                    },
                    args.checkpoint,
                )
                logging.info("Saved best checkpoint to %s (val AUC=%.4f)", args.checkpoint, val_auc)

        logging.info("Training finished. Metrics saved to %s", args.log_file)


if __name__ == "__main__":
    main()

